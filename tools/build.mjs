// JainE build - run before every deploy:   node tools/build.mjs
// Check without writing (exit 1 if stale): node tools/build.mjs --check
//
// WHAT IT MAKES. The files the browser loads stay exactly where they always were, so deploying is
// unchanged - they are just no longer edited by hand:
//   nexus-core.js   <- src/core/*.js, joined in file-name order. Edit the part, not the result.
//   the 43 app pages (crm.html, accountability.html, ...)
//                   <- src/pages/shell.html (the one page skeleton: head, sidebar, top bar)
//                      + src/pages/pages.json (what differs per page: title, PAGE, extra scripts).
// Pages that are not the app shell (login.html, signup.html, vendor-quote.html, ...) are untouched.
//
// VERSIONS ARE STAMPED, NOT TYPED. Every local script and stylesheet a page loads gets ?v=<hash of
// the file's content>, and so does every entry of PAGE_SCRIPT_VERSION (the in-place module loader's
// copy of the same addresses). Browsers keep these files for a year, so a version that is not
// bumped means people run old code - by hand this was forgotten more than once, and the loader's
// accountability.js version sat on an old copy while the page's own tag moved on. Content hashes
// cannot be forgotten and cannot disagree.
//
// HAND EDITS ARE NOT LOST. .build-manifest.json remembers what the build last wrote. If a generated
// file has been changed since (somebody edited nexus-core.js directly), the build stops and says
// which file, rather than overwriting the change. Move the edit into src/, or re-run with --force.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const FORCE = process.argv.includes('--force');
const at = (...p) => path.join(ROOT, ...p);
const read = (p) => fs.readFileSync(at(p), 'utf8');
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const short = (s) => sha(s).slice(0, 10);

const CORE_MARK = '/* GENERATED by tools/build.mjs from src/core/*.js - edit those files, then run: node tools/build.mjs */\n';
const PAGE_MARK = '<!-- GENERATED by tools/build.mjs from src/pages/shell.html + src/pages/pages.json - edit those, then run: node tools/build.mjs -->';

// ---------------------------------------------------------------- nexus-core.js
const parts = fs.readdirSync(at('src/core')).filter((f) => f.endsWith('.js')).sort();
if (!parts.length) throw new Error('src/core is empty');
let core = parts.map((f) => read(path.join('src/core', f))).join('');

// a file's version = hash of its content; nexus-core.js is hashed last, after its own stamps
const versionOf = (file) => {
  if (!fs.existsSync(at(file))) throw new Error(`${file} is referenced but does not exist`);
  return short(fs.readFileSync(at(file)));
};
core = core.replace(/const PAGE_SCRIPT_VERSION=\{([^}]*)\};/, (whole, body) => {
  const stamped = body.replace(/'([\w.-]+\.js)':'[^']*'/g, (m, file) => `'${file}':'${versionOf(file)}'`);
  return `const PAGE_SCRIPT_VERSION={${stamped}};`;
});
const coreOut = CORE_MARK + core;
const coreVersion = short(coreOut);

// ---------------------------------------------------------------- pages
const shell = read('src/pages/shell.html');
const pages = JSON.parse(read('src/pages/pages.json'));
const cssVersion = versionOf('nexus.css');
const BRAND = {
  operations: '    <a href="index.html" class="sb-brand" style="text-decoration:none" title="Back to Home">\n'
            + '      <img src="assets/jaine-logo-full-white.png?v=2" alt="JAIN-E" class="sb-logo-img">\n'
            + '    </a>',
  customer:   '    <div class="sb-brand" title="JAIN-E Customer Portal">\n'
            + '      <img src="assets/jaine-logo-full-white.png?v=2" alt="JAIN-E" class="sb-logo-img">\n'
            + '    </div>',
};
const FOOT = { operations: 'Operations Portal', customer: 'Customer Portal' };
const CHART = '<script src="vendor/chart-4.4.1.umd.min.js" defer></script>\n';
const tag = (file, v) => `<script src="${file}?v=${v}" defer></script>\n`;

const outputs = { 'nexus-core.js': coreOut };
for (const p of pages) {
  const portal = p.portal || 'operations';
  const scripts = [...(p.before || []).map((f) => tag(f, versionOf(f))),
                   tag('nexus-core.js', coreVersion),
                   ...(p.after || []).map((f) => tag(f, versionOf(f)))].join('');
  let html = shell
    .replace('{{TITLE}}', p.title)
    .replace('{{CHART}}', p.chart === false ? '' : CHART)
    .replace('{{BRAND}}', BRAND[portal])
    .replace('{{FOOT}}', FOOT[portal])
    .replace('{{PAGE}}', p.page)
    .replace('{{SCRIPTS}}', scripts)
    // every local script and stylesheet the template itself names (nexus.css, vendor/...) gets its
    // content version too; the page's own scripts were stamped above
    .replace(/\b(src|href)="((?!https?:|\/\/)[\w./-]+\.(?:js|css))"/g, (m, attr, file) => `${attr}="${file}?v=${versionOf(file)}"`);
  if (/\{\{\w+\}\}/.test(html)) throw new Error(`${p.file}: a placeholder was left unfilled`);
  html = html.replace('<!DOCTYPE html>\n', `<!DOCTYPE html>\n${PAGE_MARK}\n`);
  outputs[p.file] = html;
}

// ---------------------------------------------------------------- write / check
const MANIFEST = '.build-manifest.json';
const manifest = fs.existsSync(at(MANIFEST)) ? JSON.parse(read(MANIFEST)) : {};
const stale = [], handEdited = [];
for (const [file, content] of Object.entries(outputs)) {
  const onDisk = fs.existsSync(at(file)) ? fs.readFileSync(at(file), 'utf8').replace(/\r\n/g, '\n') : null;
  if (onDisk !== content) stale.push(file);
  if (onDisk !== null && manifest[file] && sha(onDisk) !== manifest[file] && onDisk !== content) handEdited.push(file);
}
if (CHECK) {
  console.log(stale.length ? `${stale.length} generated file(s) out of date - run: node tools/build.mjs\n  ${stale.join('\n  ')}`
                           : 'all generated files up to date');
  process.exit(stale.length ? 1 : 0);
}
if (handEdited.length && !FORCE) {
  console.error('These generated files were edited by hand since the last build - their changes would be lost:\n  '
    + handEdited.join('\n  ')
    + '\nMove the change into src/core/ or src/pages/, or run again with --force to overwrite.');
  process.exit(1);
}
const next = {};
for (const [file, content] of Object.entries(outputs)) {
  if (stale.includes(file)) fs.writeFileSync(at(file), content);
  next[file] = sha(content);
}
fs.writeFileSync(at(MANIFEST), JSON.stringify(next, null, 2) + '\n');
console.log(`built nexus-core.js from ${parts.length} parts and ${pages.length} pages - ${stale.length} file(s) changed`);
